  function normalize(lang) {
    if (!lang) return 'en';
    var s = String(lang).toLowerCase();
    if (s.indexOf('zh') === 0 || s === 'zh-hk' || s === 'zh-hant') return 'zh';
    return 'en';
  }

  function dict(lang) {
    return STR[normalize(lang)] || STR.en;
  }

  function t(lang, key) {
    var d = dict(lang);
    return d[key] || STR.en[key] || key;
  }

  function format(lang, key, map) {
    var text = t(lang, key);
    if (!map) return text;
    Object.keys(map).forEach(function (name) {
      text = text.split('{' + name + '}').join(map[name] == null ? '' : String(map[name]));
    });
    return text;
  }

  return { STR: STR, normalize: normalize, dict: dict, t: t, format: format };
